-- Fee, advance balance, event collection and receipt ledger.
-- Apply this migration in Supabase SQL Editor before deploying UI that uses these tables.
begin;

create table if not exists public.madrasah_events (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  default_fee numeric(12,2) not null default 0 check (default_fee >= 0),
  applies_to text not null default 'all' check (applies_to in ('all','class','selected')),
  class_names text[] not null default '{}',
  starts_on date,
  ends_on date,
  status text not null default 'active' check (status in ('active','closed','draft')),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on is null or starts_on is null or ends_on >= starts_on)
);

create table if not exists public.event_student_fees (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.madrasah_events(id) on delete restrict,
  student_id bigint not null references public.students(id) on delete restrict,
  payable_amount numeric(12,2) not null check (payable_amount >= 0),
  created_at timestamptz not null default now(),
  unique(event_id, student_id)
);

create table if not exists public.event_payments (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.madrasah_events(id) on delete restrict,
  student_id bigint not null references public.students(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  payment_date date not null default current_date,
  payment_method text not null default 'cash' check (payment_method in ('cash','bkash','nagad','bank','other')),
  receipt_no text not null unique,
  note text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  is_deleted boolean not null default false,
  deleted_at timestamptz
);

create table if not exists public.student_advance_ledger (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete restrict,
  entry_type text not null check (entry_type in ('deposit','allocation','reversal')),
  amount numeric(12,2) not null check (amount > 0),
  target_type text check (target_type in ('monthly_fee','event','other')),
  target_month integer,
  target_year integer,
  event_id bigint references public.madrasah_events(id) on delete restrict,
  source_fee_payment_id bigint references public.fee_payments(id) on delete restrict,
  source_event_payment_id bigint references public.event_payments(id) on delete restrict,
  receipt_no text,
  note text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  reversed_entry_id bigint references public.student_advance_ledger(id) on delete restrict,
  idempotency_key text unique,
  check (target_month is null or target_month between 1 and 12),
  check ((target_type <> 'event') or event_id is not null)
);

create index if not exists idx_event_student_fees_event on public.event_student_fees(event_id);
create index if not exists idx_event_student_fees_student on public.event_student_fees(student_id);
create index if not exists idx_event_payments_student_event on public.event_payments(student_id,event_id) where is_deleted = false;
create index if not exists idx_advance_ledger_student_created on public.student_advance_ledger(student_id,created_at,id);

create table if not exists public.payment_receipts (
  id bigint generated by default as identity primary key,
  receipt_no text not null unique,
  student_id bigint not null references public.students(id) on delete restrict,
  payment_date date not null default current_date,
  total_received numeric(12,2) not null default 0 check (total_received >= 0),
  received_by uuid references auth.users(id),
  received_by_name text,
  guardian_name_snapshot text,
  student_name_snapshot text not null,
  student_code_snapshot text,
  class_snapshot text,
  roll_snapshot text,
  note text,
  status text not null default 'issued' check (status in ('issued','void')),
  void_reason text,
  voided_by uuid references auth.users(id),
  voided_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.payment_receipt_items (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null references public.payment_receipts(id) on delete restrict,
  fee_type text not null check (fee_type in ('monthly_fee','admission_fee','event_fee','other','advance_deposit','advance_allocation')),
  description text not null,
  fee_month integer,
  fee_year integer,
  event_id bigint references public.madrasah_events(id) on delete restrict,
  payable_amount numeric(12,2) not null default 0 check (payable_amount >= 0),
  previous_due numeric(12,2) not null default 0 check (previous_due >= 0),
  previous_advance numeric(12,2) not null default 0 check (previous_advance >= 0),
  received_amount numeric(12,2) not null default 0 check (received_amount >= 0),
  allocated_advance numeric(12,2) not null default 0 check (allocated_advance >= 0),
  remaining_due numeric(12,2) not null default 0 check (remaining_due >= 0),
  remaining_advance numeric(12,2) not null default 0 check (remaining_advance >= 0),
  created_at timestamptz not null default now(),
  check (fee_month is null or fee_month between 1 and 12)
);

-- Admission month is the first eligible month for recurring monthly tuition.
create or replace function public.guard_fee_payment_admission_month()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_admission_date date;
begin
  select admission_date into v_admission_date
  from public.students
  where id = new.student_id and coalesce(is_deleted,false) = false;

  if v_admission_date is null then
    raise exception 'শিক্ষার্থীর ভর্তি তারিখ পাওয়া যায়নি। আগে ভর্তি তারিখ যাচাই করুন।';
  end if;

  if (new.year, new.month) < (extract(year from v_admission_date)::int, extract(month from v_admission_date)::int) then
    raise exception 'এই শিক্ষার্থীর ভর্তি কার্যকর হয়েছে % থেকে। এর আগের মাসের নিয়মিত বেতন নেওয়া যাবে না.',
      to_char(v_admission_date, 'TMMonth YYYY');
  end if;
  return new;
end;
$$;

drop trigger if exists trg_guard_fee_payment_admission_month on public.fee_payments;
create trigger trg_guard_fee_payment_admission_month
before insert or update of student_id, month, year on public.fee_payments
for each row execute function public.guard_fee_payment_admission_month();

